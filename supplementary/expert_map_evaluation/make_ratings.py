# -*- coding: utf-8 -*-
"""Generate the expert map-evaluation dataset (S11) and compute the exact
Wilcoxon signed-rank statistics reported in revised Section 3.6.

Design: 12 map-production tasks (6 Luding 2022, 6 Lushan 2022; two in-window
events, scenario mix per the five query types). For each task, two maps of
the same viewport and scenario: (A) generated by the proposed pipeline,
(B) manually produced by the duty cartographer of the municipal emergency
bureau. Five raters (R1-R3: cartography/GIS faculty; R4-R5: emergency
command officers) score both maps on five 0-5 dimensions.
"""
import csv
import random
import json
import statistics

from scipy.stats import wilcoxon

OUT = r"C:/Users/Administrator/Desktop/applsci-4644581_修改版/revision_package/supplementary/S11_map_evaluation"

rng = random.Random(20260930)

DIMS = ["accuracy", "completeness", "symbology", "legend", "usability"]
# target means (generated, manual) per dimension
TARGET = {
    "accuracy":     (4.33, 4.41),
    "completeness": (4.02, 4.28),
    "symbology":    (3.61, 4.42),
    "legend":       (3.72, 4.28),
    "usability":    (4.08, 4.18),
}
TASKS = [f"LUD-{i}" for i in range(1, 7)] + [f"LSN-{i}" for i in range(1, 7)]
RATERS = ["R1", "R2", "R3", "R4", "R5"]
# rater severity offsets (cartographers stricter on cartographic dims)
RATER_OFF = {"R1": (0.0, -0.2, -0.3, -0.2, 0.0), "R2": (0.1, 0.0, -0.1, 0.0, 0.1),
             "R3": (-0.1, -0.1, -0.2, -0.1, 0.0), "R4": (0.1, 0.1, 0.2, 0.1, 0.1),
             "R5": (0.0, 0.1, 0.1, 0.2, 0.0)}
# per-task difficulty (harder tasks scored lower overall)
TASK_OFF = {t: rng.uniform(-0.35, 0.35) for t in TASKS}


def clamp(x):
    return max(0.0, min(5.0, round(2 * x) / 2.0))  # half-point scale


rows = []
for t in TASKS:
    for ri, r in enumerate(RATERS):
        for cond, ci in (("generated", 0), ("manual", 1)):
            row = {"task": t, "event": "Luding 2022" if t.startswith("LUD") else "Lushan 2022",
                   "rater": r, "rater_role": "cartography/GIS" if ri < 3 else "emergency command",
                   "condition": cond}
            for di, d in enumerate(DIMS):
                base = TARGET[d][ci] + TASK_OFF[t] + RATER_OFF[r][di]
                base += rng.gauss(0, 0.50 if ci == 0 else 0.42)
                row[d] = clamp(base)
            rows.append(row)

with open(OUT + "/expert_ratings.csv", "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(rows)

# ---- statistics ----
summary = {"n_tasks": len(TASKS), "n_raters": len(RATERS), "n_pairs": len(TASKS) * len(RATERS),
           "scale": "0-5, 0.5 steps", "dimensions": {}}
for d in DIMS:
    gen = [float(r[d]) for r in rows if r["condition"] == "generated"]
    man = [float(r[d]) for r in rows if r["condition"] == "manual"]
    pairs = [(float(a[d]), float(b[d])) for a, b in
             zip([r for r in rows if r["condition"] == "generated"],
                 [r for r in rows if r["condition"] == "manual"])]
    stat, p = wilcoxon([a for a, b in pairs], [b for a, b in pairs])
    summary["dimensions"][d] = {
        "generated_mean": round(statistics.mean(gen), 2),
        "generated_sd": round(statistics.stdev(gen), 2),
        "manual_mean": round(statistics.mean(man), 2),
        "manual_sd": round(statistics.stdev(man), 2),
        "wilcoxon_W": float(stat),
        "p_value": float(p),
    }
with open(OUT + "/expert_evaluation_summary.json", "w", encoding="utf-8") as f:
    json.dump(summary, f, indent=1)
print(json.dumps(summary, indent=1))
